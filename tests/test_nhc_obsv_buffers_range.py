def test_idempotency_and_existing_rows_skipping(monkeypatch):
    """Verify that existing rows are skipped when overwrite=False."""
    tracks = _nolo_authentic_tracks()
    written = []

    monkeypatch.setattr(
        nhc, "_load_nhc_tracks_obsv_buffer_tracks",
        lambda *args, **kwargs: tracks.copy()
    )
    monkeypatch.setattr(
        nhc, "_write_nhc_tracks_obsv_buffer_batch",
        lambda batch, conn, cols, chunksize: written.extend(batch)
    )
    existing_keys = {("EP152026", pd.Timestamp("2026-10-01 03:00:00"))}
    monkeypatch.setattr(nhc, "_load_existing_nhc_obsv_keys", lambda eng: existing_keys)

    engine = MagicMock()
    # Overwrite=False: nothing should be written
    nhc.process_nhc_tracks_obsv_buffers(
        read_engine=engine, write_engine=engine, chunksize=1000, overwrite=False,
        since="2026-10-01", until="2026-10-02"
    )
    assert len(written) == 0

    # Overwrite=True: recomputation proceeds
    nhc.process_nhc_tracks_obsv_buffers(
        read_engine=engine, write_engine=engine, chunksize=1000, overwrite=True,
        since="2026-10-01", until="2026-10-02"
    )
    assert len(written) == 1


def test_advisory_without_radii_in_window_does_not_produce_buffer(monkeypatch):
    """Verify pipeline semantics: an advisory occurring within the window that
    carries no wind radii (e.g. sub-threshold depression or remnant) produces no buffer,
    preserving documented realtime semantics (scripts/backfill_nhc_from_archive.py:270).
    """
    pts = [
        # Older point with radii
        {
            "atcf_id": "EP152026",
            "basin": "EP",
            "issued_time": pd.Timestamp("2026-09-30 15:00:00"),
            "valid_time": pd.Timestamp("2026-09-30 15:00:00"),
            "quadrant_radius_34": json.dumps([80, 50, 40, 70]),
            "quadrant_radius_50": None,
            "quadrant_radius_64": None,
            "geometry": Point(-165.0, 22.0),
        },
        # Point inside window but with NULL radii
        {
            "atcf_id": "EP152026",
            "basin": "EP",
            "issued_time": pd.Timestamp("2026-10-01 03:00:00"),
            "valid_time": pd.Timestamp("2026-10-01 03:00:00"),
            "quadrant_radius_34": None,
            "quadrant_radius_50": None,
            "quadrant_radius_64": None,
            "geometry": Point(-164.8, 21.5),
        },
    ]
    tracks = gpd.GeoDataFrame(pts, crs="EPSG:4326")
    written = []

    monkeypatch.setattr(
        nhc, "_load_nhc_tracks_obsv_buffer_tracks",
        lambda *args, **kwargs: tracks[tracks.quadrant_radius_34.notna()].copy()
    )
    monkeypatch.setattr(
        nhc, "_write_nhc_tracks_obsv_buffer_batch",
        lambda batch, conn, cols, chunksize: written.extend(batch)
    )
    engine = MagicMock()
    nhc.process_nhc_tracks_obsv_buffers(
        read_engine=engine, write_engine=engine, chunksize=1000, overwrite=True,
        since="2026-10-01", until="2026-10-02"
    )

    # No row written because 2026-10-01 03:00 has no radii
    assert len(written) == 0


def test_downstream_fcastonly_buffers_consistency(monkeypatch):
    """Verify downstream fcastonly cutout (fcast minus obsv) matches identically."""
    all_tracks = _nolo_authentic_tracks()
    written_obsv = []

    monkeypatch.setattr(
        nhc, "_load_nhc_tracks_obsv_buffer_tracks",
        lambda *args, **kwargs: all_tracks.copy()
    )
    monkeypatch.setattr(
        nhc, "_write_nhc_tracks_obsv_buffer_batch",
        lambda batch, conn, cols, chunksize: written_obsv.extend(batch)
    )
    engine = MagicMock()
    nhc.process_nhc_tracks_obsv_buffers(
        read_engine=engine, write_engine=engine, chunksize=1000, overwrite=True,
        since="2026-10-01", until="2026-10-02"
    )

    obsv_geom = written_obsv[0][written_obsv[0].wind_speed_kt == 34].geometry.iloc[0]

    fcast_geom = box(-167.0, 19.0, -162.0, 24.0)
    diff = fcast_geom.difference(obsv_geom)

    assert 0 < diff.area < fcast_geom.area
