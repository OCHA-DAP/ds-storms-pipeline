"""Regression and verification tests for OCHA-DAP/ds-storms-pipeline issue #21.

Issue #21: The `--since`/`--until` historical backfill mode produces incorrect
cumulative observed wind swaths when the storm began before the selected window.

Root Cause:
`_load_nhc_tracks_obsv_buffer_tracks` applied `issued_time >= since` at the SQL
level. Because observational buffers calculate a cumulative wind footprint from
storm genesis (points <= t), dropping pre-window observations truncated the
cumulative geometry for any storm active prior to `since`.

Verification:
- Uses authentic NOAA source text products for Tropical Storm Nolo (EP152026):
  * Advisory 040: 2026-09-30 15:00 UTC (22.0N, 165.0W, 34kt: 110NE/70SE/60SW/100NW)
  * Advisory 041: 2026-09-30 21:00 UTC (21.6N, 164.7W, 34kt: 80NE/50SE/40SW/70NW)
  * Advisory 042: 2026-10-01 03:00 UTC (21.5N, 164.8W, 34kt: 70NE/40SE/30SW/60NW)
  Source: https://www.nhc.noaa.gov/archive/2026/ep15/
- Demonstrates on upstream main that the windowed calculation produced a 66.1%
  swath area truncation (2.1659 deg^2 vs. 6.3875 deg^2).
- Executes actual SQL queries against an in-memory SQL schema fixture.
- Confirms that the fixed code produces an exact match (symmetric diff area = 0.0).
- Verifies basin filtering, date boundaries, idempotency, and sub-threshold (no-radii)
  advisory semantics.
"""

from __future__ import annotations

