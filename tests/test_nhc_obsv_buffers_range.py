def test_actual_sql_query_execution_on_schema_fixture(monkeypatch):
    """Execute the exact SQL query generated by _load_nhc_tracks_obsv_buffer_tracks
    against an in-memory SQL database fixture. Proves that the old query truncates
    history while the new query loads the complete observation track.
    """
    eng = create_engine("sqlite://")
    with eng.connect() as conn:
        conn.exec_driver_sql("ATTACH DATABASE ':memory:' AS storms")
        conn.exec_driver_sql("""
            CREATE TABLE storms.nhc_tracks_geo (
                atcf_id TEXT, basin TEXT, issued_time TEXT, leadtime INT,
                quadrant_radius_34 TEXT, quadrant_radius_50 TEXT, quadrant_radius_64 TEXT,
                geometry TEXT
            )
        """)
        conn.exec_driver_sql("""
            INSERT INTO storms.nhc_tracks_geo VALUES
            ('EP152026', 'EP', '2026-09-30 15:00:00', 0, '[110, 70, 60, 100]', NULL, NULL, 'POINT(-165 22)'),
            ('EP152026', 'EP', '2026-09-30 21:00:00', 0, '[80, 50, 40, 70]', NULL, NULL, 'POINT(-164.7 21.6)'),
            ('EP152026', 'EP', '2026-10-01 03:00:00', 0, '[70, 40, 30, 60]', NULL, NULL, 'POINT(-164.8 21.5)')
        """)
        conn.commit()

        # 1. Unfixed upstream query (with issued_time >= since on outer table)
        q_unfixed = """
            SELECT atcf_id, basin, issued_time, issued_time AS valid_time,
                   quadrant_radius_34, quadrant_radius_50, quadrant_radius_64,
                   geometry
            FROM storms.nhc_tracks_geo
            WHERE leadtime = 0 AND (quadrant_radius_34 IS NOT NULL OR quadrant_radius_50 IS NOT NULL OR quadrant_radius_64 IS NOT NULL)
              AND issued_time >= '2026-10-01' AND issued_time < '2026-10-02'
            ORDER BY atcf_id, issued_time
        """
        df_unfixed = pd.read_sql(q_unfixed, conn)
        # Upstream main drops the two Sep 30 advisories:
        assert len(df_unfixed) == 1
        assert df_unfixed["issued_time"].tolist() == ["2026-10-01 03:00:00"]

        # 2. Fixed query generated by nhc._load_nhc_tracks_obsv_buffer_tracks.
        # Restore GeoPandas' original loader automatically when this test ends.
        monkeypatch.setattr(gpd, "read_postgis", lambda sql, c, **k: pd.read_sql(sql, conn))
        loaded = nhc._load_nhc_tracks_obsv_buffer_tracks(
            eng, since="2026-10-01", until="2026-10-02"
        )
        # Fixed query loads all 3 observations for Nolo:
        assert len(loaded) == 3
        assert loaded["issued_time"].tolist() == [
            "2026-09-30 15:00:00",
            "2026-09-30 21:00:00",
            "2026-10-01 03:00:00",
        ]


def test_cumulative_swath_identical_between_full_and_range_modes(monkeypatch):
    """Verify that range mode computes the exact same cumulative wind swath at
    target timestamps as full-history mode, while writing only the target window.
    Demonstrates that without the fix, 66.1% of Nolo's swath was dropped.
    """
    all_tracks = _nolo_authentic_tracks()
    written_full = []
    written_windowed = []

    # 1. Full-history run
    monkeypatch.setattr(
        nhc, "_load_nhc_tracks_obsv_buffer_tracks",
        lambda *args, **kwargs: all_tracks.copy()
    )
    monkeypatch.setattr(
        nhc, "_write_nhc_tracks_obsv_buffer_batch",
        lambda batch, conn, cols, chunksize: written_full.extend(batch)
    )
    engine = MagicMock()
    nhc.process_nhc_tracks_obsv_buffers(
        read_engine=engine, write_engine=engine, chunksize=1000, overwrite=True
    )

    df_full_oct1 = next(
        b for b in written_full
        if pd.Timestamp(b["valid_time"].iloc[0]) == pd.Timestamp("2026-10-01 03:00:00")
    )
    geom_full_oct1 = df_full_oct1[df_full_oct1.wind_speed_kt == 34].geometry.iloc[0]

    # Verify what upstream main produced (truncation demo):
    windowed_only = all_tracks[all_tracks["issued_time"] >= "2026-10-01"].copy()
    for sp in nhc.BUFFER_SPEEDS:
        windowed_only = nhc.expand_quad_col(windowed_only, f"quadrant_radius_{sp}")
    buf_truncated = nhc.calculate_wind_buffers_gdf(
        windowed_only, quad_cols_format="quadrant_radius_{speed}_{quad}"
    )
    geom_truncated = buf_truncated[buf_truncated.wind_speed_kt == 34].geometry.iloc[0]

    # 66.1% swath area was truncated on upstream main
    truncation_pct = (1.0 - geom_truncated.area / geom_full_oct1.area) * 100.0
    assert 65.0 < truncation_pct < 67.0, f"Expected ~66.1% truncation, got {truncation_pct:.2f}%"

    # 2. Fixed range run (--since 2026-10-01 --until 2026-10-02)
    monkeypatch.setattr(
        nhc, "_load_nhc_tracks_obsv_buffer_tracks",
        lambda *args, **kwargs: all_tracks.copy()
    )
    monkeypatch.setattr(
        nhc, "_write_nhc_tracks_obsv_buffer_batch",
        lambda batch, conn, cols, chunksize: written_windowed.extend(batch)
    )
    nhc.process_nhc_tracks_obsv_buffers(
        read_engine=engine, write_engine=engine, chunksize=1000, overwrite=True,
        since="2026-10-01", until="2026-10-02"
    )

    # Verify only 1 batch written (for 2026-10-01 03:00:00), pre-window points skipped
    assert len(written_windowed) == 1
    valid_times_written = [
        pd.Timestamp(b["valid_time"].iloc[0]) for b in written_windowed
    ]
    assert valid_times_written == [pd.Timestamp("2026-10-01 03:00:00")]

    df_win_oct1 = written_windowed[0]
    geom_win_oct1 = df_win_oct1[df_win_oct1.wind_speed_kt == 34].geometry.iloc[0]

    # Exact equality between full-history and fixed range-mode geometries
    area_diff = abs(geom_full_oct1.area - geom_win_oct1.area)
    sym_diff_area = geom_full_oct1.symmetric_difference(geom_win_oct1).area

    assert area_diff < 1e-9, f"Areas must match: full={geom_full_oct1.area}, win={geom_win_oct1.area}"
    assert sym_diff_area < 1e-9, f"Symmetric difference must be zero: {sym_diff_area}"


def test_basin_filtering_applied_consistently(monkeypatch):
    """Verify basin filter is applied to both subquery and outer query."""
    captured_queries = []

